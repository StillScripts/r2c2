import { readFile, writeFile } from "node:fs/promises"

const source = new URL("../../elements/dist/site-elements.js", import.meta.url)
const target = new URL("../elements.gen.ts", import.meta.url)

const js = await readFile(source, "utf8")
await writeFile(
  target,
  `// Generated by \`vp run --filter @workspace/backend elements\` from packages/elements. Don't edit.
export const ELEMENTS_JS = ${JSON.stringify(js)}
`
)
